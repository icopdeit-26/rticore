BEGIN;
-- A-R10: distinct customer identities; no internal member, ERP role or internal session cookie.
CREATE TABLE IF NOT EXISTS rticore_native_fg_portal_account (
 email text PRIMARY KEY CHECK(email=lower(email) AND length(email) BETWEEN 5 AND 254),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(), active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS rticore_native_fg_portal_grant (
 id text PRIMARY KEY,tenant_id text NOT NULL,legal_entity_id text NOT NULL,wallet_id text NOT NULL,
 email text NOT NULL REFERENCES rticore_native_fg_portal_account(email),customer_id text NOT NULL,
 reason text NOT NULL CHECK(length(reason) BETWEEN 12 AND 800),requested_by text NOT NULL,requested_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','revoked')),
 reviewed_by text,reviewed_at timestamptz,review_notes text,revoked_by text,revoked_at timestamptz,revocation_notes text,
 FOREIGN KEY(tenant_id,wallet_id) REFERENCES rticore_flexguard_wallets(tenant_id,id),
 FOREIGN KEY(tenant_id,legal_entity_id) REFERENCES rticore_erp_org_units(tenant_id,id),
 CHECK((status='pending' AND reviewed_by IS NULL AND reviewed_at IS NULL AND review_notes IS NULL) OR (status<>'pending' AND reviewed_by IS NOT NULL AND lower(reviewed_by)<>lower(requested_by) AND reviewed_at IS NOT NULL AND length(coalesce(review_notes,'')) BETWEEN 12 AND 800)),
 CHECK((status='revoked' AND revoked_by IS NOT NULL AND revoked_at IS NOT NULL AND length(coalesce(revocation_notes,'')) BETWEEN 12 AND 800) OR (status<>'revoked' AND revoked_by IS NULL AND revoked_at IS NULL AND revocation_notes IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS rticore_native_fg_portal_grant_active ON rticore_native_fg_portal_grant(tenant_id,legal_entity_id,wallet_id,email) WHERE status IN ('pending','approved');
CREATE TABLE IF NOT EXISTS rticore_native_fg_portal_credential (
 email text PRIMARY KEY REFERENCES rticore_native_fg_portal_account(email),
 password_hash text,totp_cipher text NOT NULL,last_totp_step bigint NOT NULL DEFAULT -1,
 invite_hash text UNIQUE,invite_expires timestamptz,enrolled_at timestamptz,
 CHECK((enrolled_at IS NULL AND password_hash IS NULL AND invite_hash IS NOT NULL AND invite_expires IS NOT NULL) OR (enrolled_at IS NOT NULL AND password_hash IS NOT NULL AND invite_hash IS NULL AND invite_expires IS NULL))
);
CREATE TABLE IF NOT EXISTS rticore_native_fg_portal_session (
 token_hash text PRIMARY KEY CHECK(token_hash ~ '^[0-9a-f]{64}$'),
 email text NOT NULL REFERENCES rticore_native_fg_portal_credential(email) ON DELETE CASCADE,
 expires_at timestamptz NOT NULL,last_seen timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS rticore_native_fg_portal_rate (
 bucket text PRIMARY KEY,window_id bigint NOT NULL,attempts integer NOT NULL CHECK(attempts>0)
);
CREATE TABLE IF NOT EXISTS rticore_native_fg_portal_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,email text NOT NULL,
 action text NOT NULL CHECK(action IN ('invite','enrolled','login','logout','revoke')),recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE OR REPLACE FUNCTION rticore_native_fg_portal_wallet_valid(p_tenant text,p_entity text,p_wallet text,p_customer text)
RETURNS boolean LANGUAGE sql STABLE SET search_path=public,pg_catalog AS $p$
 SELECT EXISTS(SELECT 1 FROM rticore_flexguard_wallets w JOIN rticore_service_contracts c ON c.tenant_id=w.tenant_id AND c.id=w.contract_id AND c.customer_id=w.customer_id
 JOIN rticore_erp_project_scopes sc ON sc.tenant_id=c.tenant_id AND sc.project_id=c.project_id AND sc.legal_entity_id=p_entity AND sc.status='approved'
 JOIN rticore_fg_contract_terms b ON b.tenant_id=c.tenant_id AND b.legal_entity_id=p_entity AND b.contract_id=c.id AND b.contract_version=c.version AND b.status='approved'
 WHERE w.tenant_id=p_tenant AND w.id=p_wallet AND w.customer_id=p_customer AND w.status='active' AND rticore_fg_contract_binding_valid(p_tenant,p_entity,c.id,b.terms_id)
 AND NOT EXISTS(SELECT 1 FROM rticore_flexguard_events e WHERE e.tenant_id=w.tenant_id AND e.wallet_id=w.id))
$p$;
CREATE OR REPLACE FUNCTION rticore_native_fg_portal_allowed(p_tenant text,p_entity text,p_wallet text,p_email text)
RETURNS boolean LANGUAGE sql STABLE SET search_path=public,pg_catalog AS $p$
 SELECT EXISTS(SELECT 1 FROM rticore_native_fg_portal_grant g JOIN rticore_native_fg_portal_account a ON a.email=g.email AND a.active
 WHERE g.tenant_id=p_tenant AND g.legal_entity_id=p_entity AND g.wallet_id=p_wallet AND g.email=lower(p_email) AND g.status='approved'
 AND rticore_native_fg_portal_wallet_valid(g.tenant_id,g.legal_entity_id,g.wallet_id,g.customer_id)
 AND NOT EXISTS(SELECT 1 FROM rticore_members m WHERE lower(m.email)=g.email))
$p$;
CREATE OR REPLACE FUNCTION rticore_native_fg_portal_grant_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=public,pg_catalog AS $p$
DECLARE actor_role text;
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_GRANT_IMMUTABLE'; END IF;
 IF TG_OP='INSERT' THEN
  IF NEW.status<>'pending' OR coalesce(rticore_fg_actor_role(NEW.tenant_id,NEW.legal_entity_id,NEW.requested_by),'') NOT IN ('admin','finance') OR NOT rticore_native_fg_portal_wallet_valid(NEW.tenant_id,NEW.legal_entity_id,NEW.wallet_id,NEW.customer_id) OR EXISTS(SELECT 1 FROM rticore_members WHERE lower(email)=NEW.email) THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_GRANT_INVALID'; END IF;
  NEW.requested_at:=clock_timestamp();RETURN NEW;
 END IF;
 IF (to_jsonb(NEW)-ARRAY['status','reviewed_by','reviewed_at','review_notes','revoked_by','revoked_at','revocation_notes']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status','reviewed_by','reviewed_at','review_notes','revoked_by','revoked_at','revocation_notes']) THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_GRANT_IMMUTABLE'; END IF;
 IF OLD.status='pending' AND NEW.status IN ('approved','rejected') THEN
  IF rticore_fg_actor_role(NEW.tenant_id,NEW.legal_entity_id,NEW.reviewed_by) IS DISTINCT FROM 'approver' OR lower(NEW.reviewed_by)=lower(NEW.requested_by) OR (NEW.status='approved' AND (NOT rticore_native_fg_portal_wallet_valid(NEW.tenant_id,NEW.legal_entity_id,NEW.wallet_id,NEW.customer_id) OR EXISTS(SELECT 1 FROM rticore_members WHERE lower(email)=NEW.email))) THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_REVIEW_INVALID'; END IF;
  NEW.reviewed_at:=clock_timestamp();
 ELSIF OLD.status='approved' AND NEW.status='revoked' THEN
  IF coalesce(rticore_fg_actor_role(NEW.tenant_id,NEW.legal_entity_id,NEW.revoked_by),'') NOT IN ('admin','approver') OR (to_jsonb(NEW)-ARRAY['status','revoked_by','revoked_at','revocation_notes']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status','revoked_by','revoked_at','revocation_notes']) THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_REVOKE_INVALID'; END IF;
  NEW.revoked_at:=clock_timestamp();
 ELSE RAISE EXCEPTION 'FLEXGUARD_PORTAL_GRANT_IMMUTABLE'; END IF;
 RETURN NEW;
END $p$;
DROP TRIGGER IF EXISTS rticore_native_fg_portal_grant_guard ON rticore_native_fg_portal_grant;
CREATE TRIGGER rticore_native_fg_portal_grant_guard BEFORE INSERT OR UPDATE OR DELETE ON rticore_native_fg_portal_grant FOR EACH ROW EXECUTE FUNCTION rticore_native_fg_portal_grant_guard();
CREATE TABLE IF NOT EXISTS rticore_native_fg_portal_submission (
 id text PRIMARY KEY,tenant_id text NOT NULL,legal_entity_id text NOT NULL,wallet_id text NOT NULL,email text NOT NULL REFERENCES rticore_native_fg_portal_account(email),
 kind text NOT NULL CHECK(kind IN ('service_request','quote_acceptance','delivery_acceptance')),
 request_id text,request_version integer,notes text NOT NULL CHECK(length(notes) BETWEEN 12 AND 1000),
 idempotency_key text NOT NULL CHECK(length(idempotency_key) BETWEEN 16 AND 128),
 recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(email,idempotency_key),
 FOREIGN KEY(tenant_id,legal_entity_id,wallet_id,request_id) REFERENCES rticore_native_fg_service_request(tenant_id,legal_entity_id,wallet_id,id),
 CHECK((kind='service_request' AND request_id IS NULL AND request_version IS NULL) OR (kind<>'service_request' AND request_id IS NOT NULL AND request_version>0))
);
CREATE UNIQUE INDEX IF NOT EXISTS rticore_native_fg_portal_acceptance_once ON rticore_native_fg_portal_submission(tenant_id,request_id,request_version,kind) WHERE kind<>'service_request';
CREATE OR REPLACE FUNCTION rticore_native_fg_portal_submission_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=public,pg_catalog AS $p$
DECLARE r record;
BEGIN
 IF TG_OP<>'INSERT' THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_SUBMISSION_IMMUTABLE'; END IF;
 IF NOT rticore_native_fg_portal_allowed(NEW.tenant_id,NEW.legal_entity_id,NEW.wallet_id,NEW.email) THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_ACCESS_DENIED'; END IF;
 IF NEW.kind<>'service_request' THEN
  SELECT status,version INTO r FROM rticore_native_fg_service_request WHERE tenant_id=NEW.tenant_id AND legal_entity_id=NEW.legal_entity_id AND wallet_id=NEW.wallet_id AND id=NEW.request_id FOR UPDATE;
  IF NOT FOUND OR r.version<>NEW.request_version OR (NEW.kind='quote_acceptance' AND r.status<>'scope_quoted') OR (NEW.kind='delivery_acceptance' AND r.status<>'qa_passed') THEN RAISE EXCEPTION 'FLEXGUARD_PORTAL_STALE_ACCEPTANCE'; END IF;
 END IF;
 NEW.recorded_at:=clock_timestamp();RETURN NEW;
END $p$;
DROP TRIGGER IF EXISTS rticore_native_fg_portal_submission_guard ON rticore_native_fg_portal_submission;
CREATE TRIGGER rticore_native_fg_portal_submission_guard BEFORE INSERT OR UPDATE OR DELETE ON rticore_native_fg_portal_submission FOR EACH ROW EXECUTE FUNCTION rticore_native_fg_portal_submission_guard();
CREATE OR REPLACE FUNCTION rticore_native_fg_portal_revoke_sessions() RETURNS trigger LANGUAGE plpgsql SET search_path=public,pg_catalog AS $p$
BEGIN
 IF OLD.status='approved' AND NEW.status='revoked' THEN
  DELETE FROM rticore_native_fg_portal_session WHERE email=NEW.email;
  INSERT INTO rticore_native_fg_portal_audit(email,action) VALUES(NEW.email,'revoke');
 END IF;
 RETURN NEW;
END $p$;
DROP TRIGGER IF EXISTS rticore_native_fg_portal_revoke_sessions ON rticore_native_fg_portal_grant;
CREATE TRIGGER rticore_native_fg_portal_revoke_sessions AFTER UPDATE ON rticore_native_fg_portal_grant FOR EACH ROW EXECUTE FUNCTION rticore_native_fg_portal_revoke_sessions();
COMMIT;
